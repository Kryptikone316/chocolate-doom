void bitfont_draw_char(unsigned short *pixels, int stride, int buf_w, int buf_h,
	int x, int y, int scale, unsigned short color, char ch)
{
	unsigned char	idx = (unsigned char)ch;
	const unsigned char *glyph;
	int	row, col, sx, sy;

	if (idx < 0x20 || idx > 0x7E)
		return;
	if (scale < 1)
		scale = 1;

	glyph = font8x8_basic[idx];

	for (row=0;row<8;row++)
	{
		unsigned char	bits = glyph[row];

		for (col=0;col<8;col++)
		{
			if (!(bits & (1 << col)))
				continue;

			for (sy=0;sy<scale;sy++)
			{
				int	py = y + row*scale + sy;
				if (py < 0 || py >= buf_h)
					continue;

				for (sx=0;sx<scale;sx++)
				{
					int	px = x + col*scale + sx;
					if (px < 0 || px >= buf_w)
						continue;
					pixels[py*stride + px] = color;
				}
			}
		}
	}
}

void bitfont_draw_string(unsigned short *pixels, int stride, int buf_w, int buf_h,
	int x, int y, int scale, int spacing, unsigned short color, const char *str)
{
	int	cx = x;

	if (scale < 1)
		scale = 1;

	for (;*str;str++)
	{
		bitfont_draw_char(pixels, stride, buf_w, buf_h, cx, y, scale,
			color, *str);
		cx += 8*scale + spacing;
	}
}

int bitfont_string_width(int len, int scale, int spacing)
{
	if (scale < 1)
		scale = 1;
	if (len <= 0)
		return 0;
	return len*8*scale + (len-1)*spacing;
}
